const HITTERS = 13
const PITCHERS = 12

/** 구단별 팬 로스터 초안. 비는 자리는 같은 구단의 가상 선수로 채운다 */
export function fanRoster(teamId: string): CustomPlayer[] {
  const draft = DRAFT[teamId]
  const sample = sampleRepository.getRoster(teamId)

  const hitters: CustomPlayer[] = (draft?.h ?? []).map(([name, position, bats, throws, avg, hr, walk, strikeout, speed, vsLefty], i) => ({
    id: `fan-h${i}`,
    name,
    number: 0,
    bats,
    throws,
    position,
    hitter: { avg, hr, walk, strikeout, speed, vsLefty },
  }))
  const pitchers: CustomPlayer[] = (draft?.p ?? []).map(([name, role, throws, era, strikeout, walk], i) => ({
    id: `fan-p${i}`,
    name,
    number: 0,
    bats: throws,
    throws,
    position: 'P',
    role,
    pitcher: { era, strikeout, walk, vsLefty: 0 },
  }))

  // 빈 자리는 가상 선수(샘플)로 채운다. 등급은 샘플 성적에서 가장 가까운 구간
  const fill = (list: CustomPlayer[], want: number, pitcher: boolean) => {
    const pool = sample.filter((p) => (p.position === 'P') === pitcher)
    for (let i = 0; list.length < want && i < pool.length; i++) {
      const p = pool[pool.length - 1 - i]
      list.push({
        id: `fan-fill-${p.id}`,
        name: p.name,
        number: 0,
        bats: p.bats,
        throws: p.throws,
        position: p.position,
        role: pitcher ? (p.role === 'SP' ? 'RP' : p.role) : undefined,
        ...(pitcher ? { pitcher: { era: 3, strikeout: 2, walk: 2, vsLefty: 0 } } : { hitter: { avg: 1, hr: 1, walk: 2, strikeout: 2, speed: 1, vsLefty: 0 } }),
      } as CustomPlayer)
    }
  }
  fill(hitters, HITTERS, false)
  fill(pitchers, PITCHERS, true)
  // 등번호는 가상 번호를 구단 안에서 겹치지 않게 다시 매긴다
  const numbers = sample.map((p) => p.number)
  return [...hitters, ...pitchers].map((p, i) => ({ ...p, number: numbers[i % numbers.length], ratedBy: 'ai' as const }))
}

export function hasFanRoster(teamId: string) {
  return teamId in DRAFT
}
